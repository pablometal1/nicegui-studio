export const WIDGET_MAP: Record<string, WidgetDefinition> = Object.fromEntries(
  WIDGET_REGISTRY.map((w) => [w.type, w])
);

export function getWidgetDefinition(type: string): WidgetDefinition | undefined {
  return WIDGET_MAP[type];
}

const DOC_SLUG_OVERRIDES: Record<string, string> = {
  // NiceGUI official docs slugs that differ from constructor name (if any)
};

export function getNiceGuiDocUrl(type: string): string {
  const slug = DOC_SLUG_OVERRIDES[type] ?? type;
  return `https://nicegui.io/documentation/${slug}`;
}

export function createWidgetNode(type: string, existingNames: Set<string>): WidgetNode {
  const def = WIDGET_MAP[type];
  const prefix = def?.namePrefix ?? type;
  let counter = 1;
  let name = `${prefix}_${counter}`;
  while (existingNames.has(name)) {
    counter += 1;
    name = `${prefix}_${counter}`;
  }
  return {
    id: `node_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}`,
    type,
    name,
    props: structuredClone(def?.defaultProps ?? {}),
    classes: def?.defaultClasses ?? '',
    style: '',
    quasarProps: '',
    events: {},
    children: [],
  };
}
